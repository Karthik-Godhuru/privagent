# ============================================================
# DATA MODELS
# ============================================================

class SafeLabel(BaseModel):
    """
    A sanitized piece of information extracted locally
    from the browser.
    """

    text: str
    role: Optional[str] = None
    selector: Optional[str] = None


class RedactedRegion(BaseModel):
    """
    Region that was detected as sensitive and removed/masked
    before the information reached the server.
    """

    x: float
    y: float
    width: float
    height: float

    reason: Optional[str] = None


class VisibleControl(BaseModel):
    """
    Browser control that is safe for the agent to reason about.
    """

    type: str
    label: Optional[str] = None
    selector: Optional[str] = None
    enabled: bool = True


class ActionCandidate(BaseModel):
    """
    Possible action generated by the browser/client side.
    """

    action: Literal[
        "click",
        "type",
        "scroll",
        "navigate",
        "wait",
        "noop",
    ]

    selector: Optional[str] = None
    value: Optional[str] = None
    url: Optional[str] = None

    x: Optional[float] = None
    y: Optional[float] = None

    amount: Optional[int] = None


class SanitizedContext(BaseModel):
    """
    IMPORTANT:
    This model intentionally contains only sanitized information.

    Raw screenshots, raw DOM, passwords, account numbers,
    personal identifiers, etc. should NOT be sent here.
    """

    goal: str = Field(..., min_length=1)

    visible_controls: List[VisibleControl] = Field(default_factory=list)

    safe_labels: List[SafeLabel] = Field(default_factory=list)

    redacted_regions: List[RedactedRegion] = Field(default_factory=list)

    action_candidates: List[ActionCandidate] = Field(default_factory=list)


class Action(BaseModel):
    """
    Final action returned to the browser extension.
    """

    action: Literal[
        "click",
        "type",
        "scroll",
        "navigate",
        "wait",
        "noop",
    ]

    selector: Optional[str] = None
    value: Optional[str] = None
    url: Optional[str] = None

    x: Optional[float] = None
    y: Optional[float] = None

    amount: Optional[int] = None

    requires_confirmation: bool = False


class AgentResponse(BaseModel):
    success: bool
    message: str
    action: Action


