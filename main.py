# ============================================================
# PRIVACY VALIDATION
# ============================================================

SENSITIVE_KEYWORDS = [
    "password",
    "passwd",
    "secret",
    "token",
    "authorization",
    "credit_card",
    "card_number",
    "cvv",
    "otp",
    "aadhaar",
    "pan_number",
    "account_number",
    "bank_account",
]


def contains_sensitive_text(text: str) -> bool:
    """
    Basic server-side safety check.

    The main privacy protection should happen locally in the
    browser extension before network transmission.
    """

    lower_text = text.lower()

    for keyword in SENSITIVE_KEYWORDS:
        if keyword in lower_text:
            return True

    return False


def validate_context(context: SanitizedContext) -> None:
    """
    Fail-closed privacy validation.

    If suspicious sensitive information reaches the gateway,
    reject the request instead of sending it to an LLM/VLM.
    """

    if contains_sensitive_text(context.goal):
        raise HTTPException(
            status_code=400,
            detail="Sensitive information detected in goal. Request rejected.",
        )

    for label in context.safe_labels:
        if contains_sensitive_text(label.text):
            raise HTTPException(
                status_code=400,
                detail="Sensitive information detected in sanitized labels.",
            )

    for control in context.visible_controls:
        if control.label and contains_sensitive_text(control.label):
            raise HTTPException(
                status_code=400,
                detail="Sensitive information detected in browser controls.",
            )


# ============================================================
# ACTION VALIDATION
# ============================================================

def validate_action(action: Action) -> Action:
    """
    Validate actions before they are returned to the browser.

    This prevents arbitrary model-generated commands from
    being executed directly.
    """

    if action.action == "click":

        if not action.selector and (
            action.x is None or action.y is None
        ):
            raise HTTPException(
                status_code=400,
                detail="Click requires selector or coordinates.",
            )

    elif action.action == "type":

        if not action.selector:
            raise HTTPException(
                status_code=400,
                detail="Type action requires a selector.",
            )

        if action.value is None:
            raise HTTPException(
                status_code=400,
                detail="Type action requires a value.",
            )

    elif action.action == "navigate":

        if not action.url:
            raise HTTPException(
                status_code=400,
                detail="Navigate action requires a URL.",
            )

    elif action.action == "scroll":

        if action.amount is None:
            raise HTTPException(
                status_code=400,
                detail="Scroll action requires an amount.",
            )

    return action


# ============================================================
# SIMPLE LOCAL PLANNER
# ============================================================

def local_planner(context: SanitizedContext) -> Action:
    """
    Temporary rule-based planner.

    This allows the complete PrivAgent pipeline to work BEFORE
    connecting an external VLM/LLM.

    Later, this function can be replaced with an actual
    VLM/LLM call.
    """

    goal = context.goal.lower()

    # --------------------------------------------------------
    # Find an obvious matching control
    # --------------------------------------------------------

    for control in context.visible_controls:

        label = (control.label or "").lower()

        if not control.enabled:
            continue

        # Example:
        # Goal: "click submit"
        # Control: "Submit"
        if "click" in goal:

            words = goal.replace(",", " ").split()

            for word in words:

                if len(word) < 3:
                    continue

                if word in label:

                    return Action(
                        action="click",
                        selector=control.selector,
                        requires_confirmation=False,
                    )

    # --------------------------------------------------------
    # Navigation
    # --------------------------------------------------------

    if goal.startswith("go to ") or goal.startswith("navigate to "):

        url = goal.replace("navigate to ", "")
        url = url.replace("go to ", "").strip()

        if url.startswith("http://") or url.startswith("https://"):

            return Action(
                action="navigate",
                url=url,
                requires_confirmation=True,
            )

    # --------------------------------------------------------
    # Scroll
    # --------------------------------------------------------

    if "scroll down" in goal:

        return Action(
            action="scroll",
            amount=600,
            requires_confirmation=False,
        )

    if "scroll up" in goal:

        return Action(
            action="scroll",
            amount=-600,
            requires_confirmation=False,
        )

    # --------------------------------------------------------
    # Candidate fallback
    # --------------------------------------------------------

    if context.action_candidates:

        candidate = context.action_candidates[0]

        return Action(
            action=candidate.action,
            selector=candidate.selector,
            value=candidate.value,
            url=candidate.url,
            x=candidate.x,
            y=candidate.y,
            amount=candidate.amount,
            requires_confirmation=(
                candidate.action in ["navigate"]
            ),
        )

    # --------------------------------------------------------
    # Nothing safe to do
    # --------------------------------------------------------

    return Action(
        action="noop",
        requires_confirmation=False,
    )


# ============================================================
# AGENT ENDPOINT
# ============================================================

@app.post("/agent", response_model=AgentResponse)
async def agent(context: SanitizedContext):
    """
    Main PrivAgent endpoint.

    Flow:

        Browser
            ↓
        Local Privacy Gate
            ↓
        Sanitized Context
            ↓
        /agent
            ↓
        Planner / VLM / LLM
            ↓
        Structured Action
            ↓
        Browser Executor
    """

    # --------------------------------------------------------
    # 1. Validate privacy
    # --------------------------------------------------------

    validate_context(context)

    # --------------------------------------------------------
    # 2. Reason over sanitized context
    # --------------------------------------------------------

    action = local_planner(context)

    # --------------------------------------------------------
    # 3. Validate generated action
    # --------------------------------------------------------

    action = validate_action(action)

    # --------------------------------------------------------
    # 4. Return structured action
    # --------------------------------------------------------

    return AgentResponse(
        success=True,
        message="Sanitized context processed successfully.",
        action=action,
    )


